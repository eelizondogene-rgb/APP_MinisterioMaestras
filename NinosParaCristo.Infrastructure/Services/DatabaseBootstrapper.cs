using Microsoft.EntityFrameworkCore;
using NinosParaCristo.Infrastructure.Persistence;

namespace NinosParaCristo.Infrastructure.Services;

public static class DatabaseBootstrapper
{
    public static async Task EnsureFullSchemaAsync(ApplicationDbContext context)
    {
        // Este bootstrapper permite abrir tanto una base nueva como una base creada durante
        // las primeras etapas del TCU. Las migraciones se conservan como evidencia académica,
        // pero el arranque no depende de que el esquema local esté exactamente en la misma etapa.
        var sql = """
        CREATE TABLE IF NOT EXISTS "Ninos" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "NombreCompleto" character varying(150) NOT NULL,
            "FechaNacimiento" date NOT NULL,
            "Alergias" character varying(500),
            "Comentarios" character varying(1000),
            "Activo" boolean NOT NULL DEFAULT TRUE,
            "FechaRegistro" timestamp with time zone NOT NULL
        );

        CREATE TABLE IF NOT EXISTS "Usuarios" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "NombreCompleto" character varying(150) NOT NULL,
            "Email" character varying(200) NOT NULL,
            "PasswordHash" text NOT NULL,
            "Rol" character varying(50) NOT NULL,
            "Activo" boolean NOT NULL DEFAULT TRUE,
            "FechaRegistro" timestamp with time zone NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_Usuarios_Email" ON "Usuarios" ("Email");

        CREATE TABLE IF NOT EXISTS "Encargados" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "NinoId" integer NOT NULL REFERENCES "Ninos" ("Id") ON DELETE CASCADE,
            "Nombre" character varying(150) NOT NULL,
            "Telefono" character varying(50),
            "Email" character varying(200),
            "Parentesco" character varying(80),
            "EsPrincipal" boolean NOT NULL DEFAULT TRUE
        );

        CREATE TABLE IF NOT EXISTS "Asistencias" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "NinoId" integer NOT NULL REFERENCES "Ninos" ("Id") ON DELETE CASCADE,
            "Fecha" date NOT NULL,
            "Presente" boolean NOT NULL,
            "Observacion" character varying(500),
            "RegistradaPorUsuarioId" integer REFERENCES "Usuarios" ("Id") ON DELETE SET NULL,
            "FechaRegistro" timestamp with time zone NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_Asistencias_NinoId_Fecha" ON "Asistencias" ("NinoId","Fecha");

        CREATE TABLE IF NOT EXISTS "GruposClase" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Nombre" character varying(120) NOT NULL,
            "EdadMinima" integer NOT NULL,
            "EdadMaxima" integer NOT NULL,
            "Orden" integer NOT NULL DEFAULT 0,
            "Activo" boolean NOT NULL DEFAULT TRUE,
            CONSTRAINT "CK_GruposClase_Edades" CHECK ("EdadMinima" >= 0 AND "EdadMaxima" >= "EdadMinima")
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_GruposClase_Nombre" ON "GruposClase" ("Nombre");

        CREATE TABLE IF NOT EXISTS "AsignacionesClaseMensuales" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Anio" integer NOT NULL,
            "Mes" integer NOT NULL,
            "GrupoClaseId" integer NOT NULL REFERENCES "GruposClase" ("Id") ON DELETE RESTRICT,
            "MaestraId" integer NOT NULL REFERENCES "Usuarios" ("Id") ON DELETE RESTRICT,
            "Tema" character varying(200),
            "MaterialUrl" character varying(1000),
            "Observaciones" character varying(1000),
            "Activo" boolean NOT NULL DEFAULT TRUE,
            CONSTRAINT "CK_AsignacionesClaseMensuales_Mes" CHECK ("Mes" >= 1 AND "Mes" <= 12)
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_AsignacionesClaseMensuales_Unica"
            ON "AsignacionesClaseMensuales" ("Anio","Mes","GrupoClaseId","MaestraId");

        -- Tabla antigua conservada por compatibilidad con las primeras etapas del TCU.
        CREATE TABLE IF NOT EXISTS "TurnosClase" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Fecha" date NOT NULL,
            "MaestraId" integer NOT NULL REFERENCES "Usuarios" ("Id") ON DELETE RESTRICT,
            "Tema" character varying(200),
            "MaterialUrl" character varying(1000),
            "Observaciones" character varying(1000),
            "Activo" boolean NOT NULL DEFAULT TRUE
        );

        CREATE TABLE IF NOT EXISTS "Protocolos" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Fecha" date NOT NULL,
            "ResponsableMeriendaId" integer REFERENCES "Usuarios" ("Id") ON DELETE SET NULL,
            "ResponsableProtocoloId" integer REFERENCES "Usuarios" ("Id") ON DELETE SET NULL,
            "Merienda" character varying(300),
            "Tareas" character varying(1000),
            "Bitacora" character varying(2000),
            "Completado" boolean NOT NULL DEFAULT FALSE,
            "Activo" boolean NOT NULL DEFAULT TRUE
        );
        CREATE INDEX IF NOT EXISTS "IX_Protocolos_Fecha" ON "Protocolos" ("Fecha");

        CREATE TABLE IF NOT EXISTS "InventarioItems" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Nombre" character varying(150) NOT NULL,
            "Descripcion" character varying(500),
            "Cantidad" integer NOT NULL DEFAULT 0,
            "StockMinimo" integer NOT NULL DEFAULT 0,
            "Unidad" character varying(50) NOT NULL DEFAULT 'unidad',
            "Activo" boolean NOT NULL DEFAULT TRUE
        );

        CREATE TABLE IF NOT EXISTS "MovimientosInventario" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "InventarioItemId" integer NOT NULL REFERENCES "InventarioItems" ("Id") ON DELETE CASCADE,
            "Tipo" character varying(20) NOT NULL,
            "Cantidad" integer NOT NULL,
            "Nota" character varying(500),
            "UsuarioId" integer REFERENCES "Usuarios" ("Id") ON DELETE SET NULL,
            "FechaRegistro" timestamp with time zone NOT NULL
        );

        CREATE TABLE IF NOT EXISTS "Notificaciones" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "UsuarioId" integer NOT NULL REFERENCES "Usuarios" ("Id") ON DELETE CASCADE,
            "Titulo" character varying(200) NOT NULL,
            "Mensaje" character varying(1000) NOT NULL,
            "Tipo" character varying(50) NOT NULL,
            "FechaProgramada" timestamp with time zone NOT NULL,
            "FechaCreacion" timestamp with time zone NOT NULL,
            "Leida" boolean NOT NULL DEFAULT FALSE,
            "Enviada" boolean NOT NULL DEFAULT TRUE,
            "ClaveUnica" character varying(200)
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_Notificaciones_ClaveUnica" ON "Notificaciones" ("ClaveUnica") WHERE "ClaveUnica" IS NOT NULL;

        CREATE TABLE IF NOT EXISTS "PushSuscripciones" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "UsuarioId" integer NOT NULL REFERENCES "Usuarios" ("Id") ON DELETE CASCADE,
            "Endpoint" character varying(2000) NOT NULL,
            "P256dh" character varying(500) NOT NULL,
            "Auth" character varying(500) NOT NULL,
            "UserAgent" character varying(1000),
            "Activa" boolean NOT NULL DEFAULT TRUE,
            "FechaRegistro" timestamp with time zone NOT NULL,
            "FechaActualizacion" timestamp with time zone NOT NULL
        );
        CREATE UNIQUE INDEX IF NOT EXISTS "IX_PushSuscripciones_Endpoint" ON "PushSuscripciones" ("Endpoint");
        CREATE INDEX IF NOT EXISTS "IX_PushSuscripciones_UsuarioId" ON "PushSuscripciones" ("UsuarioId");

        CREATE TABLE IF NOT EXISTS "Comunicaciones" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "NinoId" integer NOT NULL REFERENCES "Ninos" ("Id") ON DELETE RESTRICT,
            "EncargadoId" integer REFERENCES "Encargados" ("Id") ON DELETE SET NULL,
            "Asunto" character varying(200) NOT NULL,
            "Mensaje" character varying(2000) NOT NULL,
            "Canal" character varying(50) NOT NULL,
            "Destinatario" character varying(200),
            "Estado" character varying(50) NOT NULL,
            "FechaCreacion" timestamp with time zone NOT NULL,
            "FechaEnvio" timestamp with time zone,
            "UsuarioId" integer REFERENCES "Usuarios" ("Id") ON DELETE SET NULL
        );
        """;

        await context.Database.ExecuteSqlRawAsync(sql);
    }
}
